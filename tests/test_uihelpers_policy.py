"""
Headless tests for the pure helpers in src/webui/uihelpers.py that the browser dialogs share:

  _parse_rk_input(text) -> (bytearray | None, str | None)
      Checksum-verifies a recovery-key string; returns (raw, None) on success
      or (None, friendly_error) on failure.

  _applicable_manage_actions(info, n_files) -> list[str]
      Given a vault_info() dict, returns the action IDs that make sense for the
      current vault state.

They are exercised with real vault_info()-shaped dicts and with a real recovery key generated by
crypto, plus intentionally corrupted inputs to verify friendly error messaging.

Call convention: plain `def test_x() -> None:` functions; banners as 75-dash lines with a prose
paragraph; standalone runner block prints `Results: N/N passed`.
"""
import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from src.webui.uihelpers import (
    _parse_rk_input,
    _applicable_manage_actions,
)
from src.vault.crypto import new_recovery_key, format_recovery_key


# ---------------------------------------------------------------------------
# _parse_rk_input
#
# Wraps crypto.parse_recovery_key with a friendly error string so the UI can
# say "looks like a typo" rather than surfacing a raw exception.  A valid
# recovery key must parse to a bytearray of the right length; an invalid one
# must return (None, non-empty-string).  Key material in the returned
# bytearray is zeroed in each test.
# ---------------------------------------------------------------------------

def _make_valid_rk():
    """Return a (key_text, raw_bytes) pair for a freshly generated key."""
    raw = new_recovery_key()
    text = format_recovery_key(bytes(raw))
    return text, raw


def test_parse_rk_valid_returns_bytearray() -> None:
    text, raw_orig = _make_valid_rk()
    parsed, err = _parse_rk_input(text)
    try:
        assert err is None, f"REGRESSION: valid key produced error: {err!r}"
        assert isinstance(parsed, bytearray), (
            "REGRESSION: _parse_rk_input did not return a bytearray for a valid key"
        )
    finally:
        if parsed is not None:
            for i in range(len(parsed)):
                parsed[i] = 0
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_valid_bytearray_has_correct_length() -> None:
    text, raw_orig = _make_valid_rk()
    parsed, err = _parse_rk_input(text)
    try:
        assert err is None
        # 20 bytes — crypto.RECOVERY_KEY_BYTES
        assert len(parsed) == 20, (
            f"REGRESSION: parsed recovery key has {len(parsed)} bytes, expected 20"
        )
    finally:
        if parsed is not None:
            for i in range(len(parsed)):
                parsed[i] = 0
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_valid_matches_original() -> None:
    text, raw_orig = _make_valid_rk()
    parsed, err = _parse_rk_input(text)
    try:
        assert err is None
        assert bytes(parsed) == bytes(raw_orig), (
            "REGRESSION: _parse_rk_input returned bytes that do not match "
            "the original raw key"
        )
    finally:
        if parsed is not None:
            for i in range(len(parsed)):
                parsed[i] = 0
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_bad_checksum_returns_none_and_error() -> None:
    text, raw_orig = _make_valid_rk()
    try:
        # Corrupt the last character of the checksum
        corrupted = text[:-1] + ("A" if text[-1] != "A" else "B")
        parsed, err = _parse_rk_input(corrupted)
        assert parsed is None, (
            "REGRESSION: bad-checksum key returned a non-None bytearray"
        )
        assert isinstance(err, str) and len(err) > 0, (
            "REGRESSION: bad-checksum key did not return a non-empty error string"
        )
    finally:
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_bad_checksum_error_mentions_typo() -> None:
    text, raw_orig = _make_valid_rk()
    try:
        corrupted = text[:-1] + ("A" if text[-1] != "A" else "B")
        _, err = _parse_rk_input(corrupted)
        assert err is not None
        assert "typo" in err.lower() or "check" in err.lower(), (
            f"REGRESSION: bad-checksum error does not say 'typo' or 'check': {err!r}"
        )
    finally:
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_empty_string_returns_error() -> None:
    parsed, err = _parse_rk_input("")
    assert parsed is None, "REGRESSION: empty string returned a bytearray"
    assert isinstance(err, str) and len(err) > 0, (
        "REGRESSION: empty string returned no error message"
    )


def test_parse_rk_garbage_returns_error() -> None:
    parsed, err = _parse_rk_input("not-a-key-at-all")
    assert parsed is None, "REGRESSION: garbage input returned a bytearray"
    assert err is not None, "REGRESSION: garbage input returned no error"


def test_parse_rk_wrong_length_returns_error() -> None:
    parsed, err = _parse_rk_input("RK1 AAAA-BBBB")
    assert parsed is None, "REGRESSION: short key returned a bytearray"
    assert err is not None, "REGRESSION: short key returned no error"


def test_parse_rk_normalises_case() -> None:
    """parse_recovery_key normalises Crockford case; _parse_rk_input must
    honour that so users who type lowercase are not rejected."""
    text, raw_orig = _make_valid_rk()
    try:
        parsed, err = _parse_rk_input(text.lower())
        assert err is None, (
            f"REGRESSION: lowercase valid key was rejected: {err!r}"
        )
        assert parsed is not None
    finally:
        if parsed is not None:
            for i in range(len(parsed)):
                parsed[i] = 0
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


def test_parse_rk_normalises_without_hyphens() -> None:
    """Users may type the key without hyphens; parse_recovery_key strips them."""
    text, raw_orig = _make_valid_rk()
    try:
        no_hyphens = text.replace("-", "").replace(" ", " ")
        parsed, err = _parse_rk_input(no_hyphens)
        assert err is None, (
            f"REGRESSION: key without hyphens was rejected: {err!r}"
        )
    finally:
        if parsed is not None:
            for i in range(len(parsed)):
                parsed[i] = 0
        for i in range(len(raw_orig)):
            raw_orig[i] = 0


# ---------------------------------------------------------------------------
# _applicable_manage_actions
#
# Given a vault_info() dict, this function returns the list of action IDs
# whose buttons should appear in manage_vault_dialog.  It must hide actions
# that don't apply (e.g. upgrade_v2 on a v2 vault) and show all that do.
# ---------------------------------------------------------------------------

def test_manage_actions_v1_vault() -> None:
    info = {"format": 1, "kdf": "pbkdf2-hmac-sha256", "recovery_slot": False}
    actions = _applicable_manage_actions(info)
    assert "change_password" in actions, (
        "REGRESSION: change_password missing for v1 vault"
    )
    assert "upgrade_v2" in actions, (
        "REGRESSION: upgrade_v2 missing for v1 vault"
    )
    assert "setup_recovery" not in actions, (
        "REGRESSION: setup_recovery shown for v1 vault (not supported)"
    )
    assert "reissue_recovery" not in actions, (
        "REGRESSION: reissue_recovery shown for v1 vault"
    )


def test_manage_actions_v2_no_recovery() -> None:
    info = {"format": 2, "kdf": "scrypt", "recovery_slot": False}
    actions = _applicable_manage_actions(info)
    assert "change_password" in actions, (
        "REGRESSION: change_password missing for v2 vault without recovery slot"
    )
    assert "setup_recovery" in actions, (
        "REGRESSION: setup_recovery missing for v2 vault without recovery slot"
    )
    assert "reissue_recovery" not in actions, (
        "REGRESSION: reissue_recovery shown for v2 vault that has no recovery slot"
    )
    assert "upgrade_v2" not in actions, (
        "REGRESSION: upgrade_v2 shown for a v2 vault"
    )


def test_manage_actions_v2_with_recovery() -> None:
    info = {"format": 2, "kdf": "scrypt", "recovery_slot": True,
            "recovery_slot_id": "ABCD"}
    actions = _applicable_manage_actions(info)
    assert "change_password" in actions, (
        "REGRESSION: change_password missing for v2 vault with recovery slot"
    )
    assert "reissue_recovery" in actions, (
        "REGRESSION: reissue_recovery missing for v2 vault with recovery slot"
    )
    assert "setup_recovery" not in actions, (
        "REGRESSION: setup_recovery shown for v2 vault that already has a recovery slot"
    )
    assert "upgrade_v2" not in actions, (
        "REGRESSION: upgrade_v2 shown for a v2 vault"
    )


def test_manage_actions_error_returns_empty() -> None:
    info = {"error": "could not read vault.enc"}
    actions = _applicable_manage_actions(info)
    assert actions == [], (
        f"REGRESSION: error vault_info returned {actions!r} instead of []"
    )


def test_manage_actions_no_vault_returns_empty() -> None:
    info = {"error": "no vault"}
    actions = _applicable_manage_actions(info)
    assert actions == [], (
        "REGRESSION: 'no vault' info returned non-empty actions"
    )


def test_manage_actions_change_password_always_first() -> None:
    for info in [
        {"format": 1, "recovery_slot": False},
        {"format": 2, "recovery_slot": False},
        {"format": 2, "recovery_slot": True},
    ]:
        actions = _applicable_manage_actions(info)
        assert actions[0] == "change_password", (
            f"REGRESSION: change_password is not first in {actions!r} for {info!r}"
        )


def test_manage_actions_upgrade_v2_only_for_v1() -> None:
    """upgrade_v2 must appear for v1 and not for v2."""
    v1_info = {"format": 1, "recovery_slot": False}
    v2_info = {"format": 2, "recovery_slot": False}
    assert "upgrade_v2" in _applicable_manage_actions(v1_info)
    assert "upgrade_v2" not in _applicable_manage_actions(v2_info)


# ---------------------------------------------------------------------------
# Test runner
# ---------------------------------------------------------------------------

def _run(fn) -> bool:
    print(f"Running {fn.__name__} ...", flush=True)
    try:
        fn()
        print("  PASS")
        return True
    except Exception as exc:
        import traceback
        print(f"  FAIL: {exc}")
        traceback.print_exc()
        return False


if __name__ == "__main__":
    tests = [v for k, v in sorted(globals().items())
             if k.startswith("test_") and callable(v)]

    passed = [t for t in tests if _run(t)]
    failed = [t for t in tests if t not in passed]

    print()
    print(f"Results: {len(passed)}/{len(tests)} passed")
    if failed:
        print(f"FAILED: {[f.__name__ for f in failed]}")
        sys.exit(1)
    else:
        print("All tests passed.")
